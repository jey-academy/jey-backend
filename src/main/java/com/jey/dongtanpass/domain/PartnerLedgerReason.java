package com.jey.dongtanpass.domain;

/**
 * 연계 학원 장부에 쓰지 못한 이유. {@link #GOOGLE_UNAVAILABLE}만 구글 쪽 장애이고(간격을 두고 다시 시도한 끝),
 * 나머지는 사람이 장부나 설정을 고쳐야 하는 이유라 자동으로 다시 하지 않는다(관리자가 고친 뒤 다시 반영).
 * 이름은 DB에 그대로 저장되고 관리자 화면이 안내 문구를 고르는 데 쓴다. 한 번 쓴 이름은 바꾸지 않는다.
 */
public enum PartnerLedgerReason {

	/** 구글이 응답하지 않거나(시간 초과, 연결 끊김) 408·5xx·429로 답했고, 다시 시도한 횟수를 다 썼다. */
	GOOGLE_UNAVAILABLE,

	/** 그 연계 학원의 장부가 설정에 없거나, 설정한 스프레드시트가 없다. */
	NOT_CONFIGURED,

	/** 장부 파일에 정한 이름의 탭(기본 {@code JEY 패스})이 없다. */
	TAB_NOT_FOUND,

	/** 탭의 1행이 정한 머리글과 다르다(다른 파일이거나 머리글을 고쳤다). 쓰지 않는다. */
	HEADER_MISMATCH,

	/** 서비스 계정이 그 장부에 쓸 권한이 없다(또는 키가 더는 유효하지 않다). */
	ACCESS_DENIED,

	/** 구글이 위의 어느 것도 아닌 이유로 요청을 거절했다(4xx). 앱의 요청이 틀렸을 수 있어 로그와 함께 본다. */
	GOOGLE_REJECTED,

	/** 앱의 예상하지 못한 오류(로그에 남는다). 원인을 고친 뒤 다시 반영한다. */
	APP_ERROR

}
